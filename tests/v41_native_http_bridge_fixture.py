def _key(seed: int) -> tuple[Ed25519PrivateKey, str]:
    private = Ed25519PrivateKey.from_private_bytes(bytes([seed]) * 32)
    public = private.public_key().public_bytes(
        serialization.Encoding.Raw, serialization.PublicFormat.Raw,
    )
    return private, base64.urlsafe_b64encode(public).decode().rstrip("=")


def _one(db: sqlite3.Connection, sql: str) -> sqlite3.Row:
    rows = db.execute(sql).fetchall()
    if len(rows) != 1:
        raise ValueError("native_v41_fixture_cardinality")
    return rows[0]


class _NativeScript:
    def __init__(self, authority: SiteAuthority, lease: dict,
                 now: datetime, prior_digest: str) -> None:
        device = next(iter(authority.devices.values()))
        event = {"synthetic": "v41-bridge-second"}
        self.site = (True, authority.authority_generation,
                     authority.revocation_generation, authority.authority_payload_digest)
        self.device = ("active", device.signing_key_id, device.public_key,
                       device.client_fingerprint, device.enrollment_evidence_digest,
                       device.session_generation)
        self.lease = ("active", digest(lease), lease["actorId"], device.device_id,
                      lease["role"], lease["sessionGeneration"],
                      lease["revocationGeneration"], lease["issuerKeyId"],
                      authority.issuer_keys[lease["issuerKeyId"]],
                      datetime.fromisoformat(lease["expiresAt"].replace("Z", "+00:00")))
        self.now = now
        self.late_now = None
        self.prior = (prior_digest,)
        self.events = [(2, digest(event), prior_digest, canonical_json(event))]
        self.queries = []
        self.autocommit = False
        self.clock_reads = 0

    def connect(self):
        return _Connection(self)


def load_native_context(native_database: Path, *, request_issued_at: str | None = None):
    with sqlite3.connect(native_database) as db:
        db.row_factory = sqlite3.Row
        retained = _one(db, "SELECT request_json FROM shop_connected_cloud_feed_page_evidence")
        first_request = json.loads(retained["request_json"])
        first_digest = _one(db, "SELECT next_event_digest FROM shop_connected_cloud_feed_heads")["next_event_digest"]
        lease = json.loads(_one(db, "SELECT lease_json FROM shop_site_offline_lease_payloads")["lease_json"])
        payload_row = _one(db, "SELECT payload_bytes, signature FROM shop_site_authority_payloads")
        payload = json.loads(payload_row["payload_bytes"])
        checkpoint_row = _one(db, "SELECT checkpoint_bytes, signature FROM shop_site_authority_checkpoints")
        checkpoint = json.loads(checkpoint_row["checkpoint_bytes"])
        member_row = _one(db, "SELECT actor_id, actor_role, capabilities_json, session_generation FROM shop_site_authority_members")
        client_seed = {"device_v41_fixture": 18, "device_v41_second": 24}.get(first_request["deviceId"])
        if client_seed is None or lease["deviceId"] != first_request["deviceId"]:
            raise ValueError("native_v41_fixture_device")
        client_key, public = _key(client_seed)
        public_bytes = base64.urlsafe_b64decode(public + "==")
        if (
            first_request["signingKeyId"] != first_request["clientFingerprint"]
            or sha256(public_bytes).hexdigest() != first_request["clientFingerprint"]
        ):
            raise ValueError("native_v41_fixture_fingerprint")
        device = DeviceAuthority(
            device_id=first_request["deviceId"],
            signing_key_id=first_request["signingKeyId"], public_key=public,
            client_fingerprint=first_request["clientFingerprint"],
            enrollment_evidence_digest=first_request["enrollmentEvidenceDigest"],
            coordinator_binding_digest=digest({"coordinator": first_request["siteId"]}),
            session_generation=lease["sessionGeneration"],
        )
        member = CurrentMember(member_row["actor_id"], member_row["actor_role"],
                               tuple(json.loads(member_row["capabilities_json"])),
                               member_row["session_generation"])
        authority = SiteAuthority(
            workspace_id=payload["workspaceId"], site_id=payload["siteId"],
            authority_generation=payload["authoritySequence"],
            configuration_generation=payload["configurationSnapshot"]["configurationVersion"],
            revocation_generation=payload["membershipSnapshot"]["revocationGeneration"],
            authority_payload_digest=digest(payload),
            issuer_keys={"lease_fixture": _key(20)[1]},
            devices={device.device_id: device}, members={member.actor_id: member},
            authority_payload=payload, authority_signature=payload_row["signature"],
            authority_issuer_keys={"authority_fixture": _key(19)[1]},
            authority_checkpoints={device.device_id: (checkpoint, checkpoint_row["signature"])},
            enabled=True,
        )
    unsigned = {key: value for key, value in first_request.items() if key != "signature"}
    unsigned.update(afterSequence=1, priorEventDigest=first_digest, requestNonce="9" * 64)
    if request_issued_at is not None:
        unsigned["issuedAt"] = request_issued_at
    signature = client_key.sign(canonical_json(unsigned).encode())
    request = {**unsigned, "signature": base64.urlsafe_b64encode(signature).decode().rstrip("=")}
    return authority, device, lease, request, first_digest


def build_response(native_database: Path, *, now: datetime | None = None,
                   request_issued_at: str | None = None) -> dict[str, str]:
    authority, device, lease, request, first_digest = load_native_context(
        native_database, request_issued_at=request_issued_at)
    # Source-pinned test clock, never derived from the caller's HTTP body.
    now = now or datetime.fromtimestamp(1800000000.9, tz=timezone.utc)
    script = _NativeScript(authority, lease, now, first_digest)
    provider = _Authorities(authority)
    active = True

    def peer(http_request: Request):
        if not active:
            return None
        return GatewayPeerAttestation(
            request=http_request, gateway_id="test-native-v41",
            workspace_id=authority.workspace_id, site_id=authority.site_id,
            device_id=device.device_id, client_fingerprint=device.client_fingerprint,
            session_generation=device.session_generation, observed_at=now,
        )

    resolver = ConnectedSiteGatewayPrincipalResolver(
        gateway_id="test-native-v41", load_attested_peer=peer,
        authority_provider=provider, now=lambda: now,
    )
    app = FastAPI()
    principal = ConnectedSitePrincipal(
        authority.workspace_id, authority.site_id, device.device_id, True,
        "test-native-v41",
    )
    app.include_router(create_connected_site_event_feed_router(
        connection_factory=script.connect, authority_provider=provider,
        resolve_principal=resolver,
        load_lease=lambda _principal, _request: lease,
        seal_checked_page=lambda page, signed_request, signed_lease:
            seal_test_only_checked_page(
                page, signed_request, signed_lease, principal=principal,
                now=now, issuer_key_id="feed_fixture", issuer_seed=23,
            ),
        pinned_issuer_keys={"feed_fixture": _key(23)[1]},
        trusted_now=lambda: now, runtime_enabled=True,
    ))
    path = "/api/connected-site/v1/event-feed"

    with TestClient(app) as client:
        response = client.post(path, json=request)
        if response.status_code != 200:
            raise ValueError(f"native_v41_http_rejected:{response.status_code}")
        sealed = response.json()
        if set(sealed) != {"requestJson", "pageJson", "proofJson"}:
            raise ValueError("native_v41_http_response_shape")
        wrong_device = client.post(path, json={**request, "deviceId": "wrong"})
        if (wrong_device.status_code != 422
                or wrong_device.json()["detail"]["error"] != "event_read_scope"):
            raise ValueError(f"native_v41_wrong_device_denial_changed:{wrong_device.status_code}")
        active = False
        if client.post(path, json=request).status_code != 401:
            raise ValueError("native_v41_revoked_peer_accepted")
    return sealed


def build_pg_response(native_database: Path, *, admin_url: str,
                      runtime_url: str, first: bool,
                      previous: tuple[str, str, str] | None,
                      request_issued_at: str,
                      ) -> tuple[dict[str, str], tuple[str, str, str]]:
    """Read actual disposable PG17/RLS rows; never accept a production URL.

    The caller owns the ephemeral loopback cluster and must destroy it even on
    failure.  This fixture deliberately does not install a route or keys.
    """
    import psycopg

    authority, device, lease, request, first_digest = load_native_context(
        native_database, request_issued_at=request_issued_at)
    admin_target = urlsplit(admin_url)
    runtime_target = urlsplit(runtime_url)
    if (
        first_digest != digest({"synthetic": "v41-bridge-first"})
        or (first and previous is not None)
        or (not first and previous != (
            authority.authority_payload_digest, first_digest, "device_v41_fixture"
        ))
        or (first and device.device_id != "device_v41_fixture")
        or (not first and device.device_id != "device_v41_second")
        or (not first and lease["leaseId"] != "lease_v41_second_fixture")
        or admin_target.scheme != "postgresql" or admin_target.hostname != "127.0.0.1"
        or admin_target.username != "postgres" or not admin_target.port
        or not admin_target.password
        or runtime_target.scheme != "postgresql" or runtime_target.hostname != "127.0.0.1"
        or runtime_target.username != "supermega_trial_login"
        or runtime_target.port != admin_target.port or not runtime_target.password
        or runtime_target.path != admin_target.path
    ):
        raise ValueError("native_v41_pg_fixture_identity")
    workspace, site = authority.workspace_id, authority.site_id
    with psycopg.connect(admin_url) as connection:
        if first:
            connection.execute(
                "insert into app_private.connected_sites "
                "(workspace_id,site_id,protocol_version,connected_enabled,authority_generation,"
                "configuration_generation,revocation_generation,authority_payload_digest) "
                "values (%s,%s,1,true,%s,%s,%s,%s)",
                (workspace, site, authority.authority_generation,
                 authority.configuration_generation, authority.revocation_generation,
                 authority.authority_payload_digest),
            )
        else:
            site_row = connection.execute(
                "select authority_payload_digest from app_private.connected_sites "
                "where workspace_id=%s and site_id=%s",
                (workspace, site),
            ).fetchone()
            if site_row != (authority.authority_payload_digest,):
                raise ValueError("native_v41_pg_site_changed")
        connection.execute(
            "insert into app_private.connected_site_devices "
            "(workspace_id,site_id,device_id,signing_key_id,signing_public_key,"
            "client_fingerprint,enrollment_evidence_digest,coordinator_binding_digest,"
            "session_generation,status) values (%s,%s,%s,%s,%s,%s,%s,%s,%s,'active')",
            (workspace, site, device.device_id, device.signing_key_id, device.public_key,
             device.client_fingerprint, device.enrollment_evidence_digest,
             device.coordinator_binding_digest, device.session_generation),
        )
        connection.execute(
            "insert into app_private.connected_site_leases "
            "(workspace_id,site_id,lease_id,actor_id,device_id,role,capabilities,"
            "session_generation,revocation_generation,configuration_generation,"
            "issuer_key_id,issuer_public_key,lease_json,lease_digest,issued_at,expires_at,status) "
            "values (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s::jsonb,%s,%s,%s,'active')",
            (workspace, site, lease["leaseId"], lease["actorId"], device.device_id,
             lease["role"], lease["capabilities"], lease["sessionGeneration"],
             lease["revocationGeneration"], authority.configuration_generation,
             lease["issuerKeyId"], authority.issuer_keys[lease["issuerKeyId"]],
             canonical_json(lease), digest(lease),
             datetime.fromisoformat(lease["issuedAt"].replace("Z", "+00:00")),
             datetime.fromisoformat(lease["expiresAt"].replace("Z", "+00:00"))),
        )
        connection.execute(
            "insert into app_private.connected_site_cursors "
            "(workspace_id,site_id,device_id) values (%s,%s,%s)",
            (workspace, site, device.device_id),
        )
        if first:
            previous_digest = None
            for sequence, event in enumerate((
                {"synthetic": "v41-bridge-first"},
                {"synthetic": "v41-bridge-second"},
            ), start=1):
                event_digest = digest(event)
                command_id = f"native-v41-pg-{sequence}"
                command_digest = digest({"command": command_id})
                connection.execute(
                    "insert into app_private.connected_site_commands "
                    "(workspace_id,site_id,command_id,command_digest,command_json,"
                    "proof_json,proof_digest,actor_id,device_id,lease_id,aggregate_type,"
                    "aggregate_id,expected_version,state) "
                    "values (%s,%s,%s,%s,'{}'::jsonb,'{}'::jsonb,%s,%s,%s,%s,%s,%s,%s,'accepted')",
                    (workspace, site, command_id, command_digest, digest({}),
                     lease["actorId"], device.device_id, lease["leaseId"],
                     "retailCart", command_id, 0),
                )
                connection.execute(
                    "insert into app_private.connected_site_events "
                    "(workspace_id,site_id,event_sequence,event_id,event_digest,"
                    "previous_event_digest,event_json,command_id,command_digest,"
                    "aggregate_type,aggregate_id,aggregate_version) "
                    "values (%s,%s,%s,%s,%s,%s,%s::jsonb,%s,%s,%s,%s,1)",
                    (workspace, site, sequence, f"native-v41-pg-event-{sequence}",
                     event_digest, previous_digest, canonical_json(event),
                     command_id, command_digest, "retailCart", command_id),
                )
                previous_digest = event_digest
    # Exercise the same checked HTTP route as the mock two-store bridge, but
    # with a disposable real PostgreSQL 17 transaction and forced RLS. This
    # TestClient mount is not a network listener or production ingress.
    provider = _Authorities(authority)
    principal = ConnectedSitePrincipal(workspace, site, device.device_id, True,
                                       "test-native-v41-pg")

    def peer(http_request: Request):
        return GatewayPeerAttestation(
            request=http_request, gateway_id="test-native-v41-pg",
            workspace_id=workspace, site_id=site, device_id=device.device_id,
            client_fingerprint=device.client_fingerprint,
            session_generation=device.session_generation,
            observed_at=datetime.now(timezone.utc),
        )

    resolver = ConnectedSiteGatewayPrincipalResolver(
        gateway_id="test-native-v41-pg", load_attested_peer=peer,
        authority_provider=provider, now=lambda: datetime.now(timezone.utc),
    )
    seal_sample: datetime | None = None

    def trusted_now() -> datetime:
        nonlocal seal_sample
        seal_sample = datetime.now(timezone.utc)
        return seal_sample

    def seal(page, signed_request, signed_lease):
        # The route samples trusted time before calling this signer. Reuse
        # that same host sample so a millisecond tick cannot make a freshly
        # signed test proof appear to be issued in the future.
        if seal_sample is None:
            raise ValueError("native_v41_pg_trusted_sample_missing")
        return seal_test_only_checked_page(
            page, signed_request, signed_lease, principal=principal,
            now=seal_sample, issuer_key_id="feed_fixture",
            issuer_seed=23, proof_lifetime_millis=90000,
        )

    app = FastAPI()
    app.include_router(create_connected_site_event_feed_router(
        connection_factory=lambda: psycopg.connect(runtime_url),
        authority_provider=provider, resolve_principal=resolver,
        load_lease=lambda _principal, _request: lease,
        seal_checked_page=seal,
        pinned_issuer_keys={"feed_fixture": _key(23)[1]},
        trusted_now=trusted_now, runtime_enabled=True,
    ))
    path = "/api/connected-site/v1/event-feed"
    with TestClient(app) as client:
        response = client.post(path, json=request)
        if response.status_code != 200:
            raise ValueError(f"native_v41_pg_route_rejected:{response.status_code}")
        result = response.json()
        replay = client.post(path, json=request)
        if (replay.status_code != 200
                or replay.json()["requestJson"] != result["requestJson"]
                or replay.json()["pageJson"] != result["pageJson"]):
            raise ValueError("native_v41_pg_exact_request_replay_changed")
        with psycopg.connect(admin_url) as connection:
            event_count = connection.execute(
                "select count(*) from app_private.connected_site_events "
                "where workspace_id=%s and site_id=%s",
                (workspace, site),
            ).fetchone()
        if event_count != (2,):
            raise ValueError("native_v41_pg_replay_changed_events")
        wrong_cursor_unsigned = {
            key: value for key, value in request.items() if key != "signature"
        }
        wrong_cursor_unsigned["priorEventDigest"] = "f" * 64
        wrong_cursor_unsigned["issuedAt"] = datetime.now(timezone.utc).isoformat(
            timespec="milliseconds"
        ).replace("+00:00", "Z")
        wrong_cursor_key = _key(18 if first else 24)[0]
        wrong_cursor_signature = wrong_cursor_key.sign(
            canonical_json(wrong_cursor_unsigned).encode()
        )
        wrong_cursor = {
            **wrong_cursor_unsigned,
            "signature": base64.urlsafe_b64encode(
                wrong_cursor_signature
            ).decode().rstrip("="),
        }
        conflict = client.post(path, json=wrong_cursor)
        if (conflict.status_code != 409
                or conflict.json()["detail"]["error"] != "event_page_cursor_changed"):
            raise ValueError("native_v41_pg_wrong_cursor_denial_changed")
        wrong_device = client.post(path, json={**request, "deviceId": "wrong"})
        if (wrong_device.status_code != 422
                or wrong_device.json()["detail"]["error"] != "event_read_scope"):
            raise ValueError("native_v41_pg_wrong_device_denial_changed")
        with psycopg.connect(admin_url) as connection:
            connection.execute(
                "update app_private.connected_site_devices set status='revoked' "
                "where workspace_id=%s and site_id=%s and device_id=%s",
                (workspace, site, device.device_id),
            )
        revoked = client.post(path, json=request)
        if (revoked.status_code != 403
                or revoked.json()["detail"]["error"] != "event_page_device_changed"):
            raise ValueError("native_v41_pg_revocation_denial_changed")
    page = json.loads(result["pageJson"])
    if (
        page["afterSequence"] != 1 or page["priorEventDigest"] != first_digest
        or len(page["headers"]) != 1
        or page["headers"][0]["eventDigest"] != digest({"synthetic": "v41-bridge-second"})
    ):
        raise ValueError("native_v41_pg_checked_page_mismatch")
    return result, (authority.authority_payload_digest, first_digest, device.device_id)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("database", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    if not args.database.is_file() or args.output.exists():
        raise SystemExit("native_v41_fixture_paths_invalid")
    args.output.write_text(canonical_json(build_response(args.database)) + "\n", encoding="utf-8")
