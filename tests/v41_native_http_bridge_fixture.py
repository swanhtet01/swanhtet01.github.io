from supermega_runtime.connected_site_v15 import (
    ConnectedSiteV15Error, CurrentMember, DeviceAuthority, SiteAuthority,
    canonical_json, digest,
)
from tests.connected_site_signed_page_fixture import read_and_sign_test_only_page
from tests.test_connected_site_event_feed import _Connection
from tests.test_connected_site_runtime import _Authorities


def _key(seed: int) -> tuple[Ed25519PrivateKey, str]:
    private = Ed25519PrivateKey.from_private_bytes(bytes([seed]) * 32)
    public = private.public_key().public_bytes(
        serialization.Encoding.Raw, serialization.PublicFormat.Raw,
    )
    return private, base64.urlsafe_b64encode(public).decode().rstrip("=")


def _one(db: sqlite3.Connection, sql: str) -> sqlite3.Row:
    rows = db.execute(sql).fetchall()
    if len(rows) != 1:
        raise ValueError("native_v41_fixture_cardinality")
    return rows[0]


class _NativeScript:
    def __init__(self, authority: SiteAuthority, lease: dict, now: datetime) -> None:
        device = next(iter(authority.devices.values()))
        event = {"synthetic": "v41-bridge-second"}
        self.site = (True, authority.authority_generation,
                     authority.revocation_generation, authority.authority_payload_digest)
        self.device = ("active", device.signing_key_id, device.public_key,
                       device.client_fingerprint, device.enrollment_evidence_digest,
                       device.session_generation)
        self.lease = ("active", digest(lease), lease["actorId"], device.device_id,
                      lease["role"], lease["sessionGeneration"],
                      lease["revocationGeneration"], lease["issuerKeyId"],
                      authority.issuer_keys[lease["issuerKeyId"]],
                      datetime.fromisoformat(lease["expiresAt"].replace("Z", "+00:00")))
        self.now = now
        self.late_now = None
        self.prior = ("e" * 64,)
        self.events = [(2, digest(event), "e" * 64, canonical_json(event))]
        self.queries = []
        self.autocommit = False
        self.clock_reads = 0

    def connect(self):
        return _Connection(self)


def build_response(native_database: Path) -> dict[str, str]:
    with sqlite3.connect(native_database) as db:
        db.row_factory = sqlite3.Row
        retained = _one(db, "SELECT request_json FROM shop_connected_cloud_feed_page_evidence")
        first_request = json.loads(retained["request_json"])
        lease = json.loads(_one(db, "SELECT lease_json FROM shop_site_offline_lease_payloads")["lease_json"])
        payload_row = _one(db, "SELECT payload_bytes, signature FROM shop_site_authority_payloads")
        payload = json.loads(payload_row["payload_bytes"])
        checkpoint_row = _one(db, "SELECT checkpoint_bytes, signature FROM shop_site_authority_checkpoints")
        checkpoint = json.loads(checkpoint_row["checkpoint_bytes"])
        member_row = _one(db, "SELECT actor_id, actor_role, capabilities_json, session_generation FROM shop_site_authority_members")
        client_seed = {"device_v41_fixture": 18, "device_v41_second": 24}.get(first_request["deviceId"])
        if client_seed is None or lease["deviceId"] != first_request["deviceId"]:
            raise ValueError("native_v41_fixture_device")
        client_key, public = _key(client_seed)
        public_bytes = base64.urlsafe_b64decode(public + "==")
        if (
            first_request["signingKeyId"] != first_request["clientFingerprint"]
            or sha256(public_bytes).hexdigest() != first_request["clientFingerprint"]
        ):
            raise ValueError("native_v41_fixture_fingerprint")
        device = DeviceAuthority(
            device_id=first_request["deviceId"],
            signing_key_id=first_request["signingKeyId"], public_key=public,
            client_fingerprint=first_request["clientFingerprint"],
            enrollment_evidence_digest=first_request["enrollmentEvidenceDigest"],
            coordinator_binding_digest=digest({"coordinator": first_request["siteId"]}),
            session_generation=lease["sessionGeneration"],
        )
        member = CurrentMember(member_row["actor_id"], member_row["actor_role"],
                               tuple(json.loads(member_row["capabilities_json"])),
                               member_row["session_generation"])
        authority = SiteAuthority(
            workspace_id=payload["workspaceId"], site_id=payload["siteId"],
            authority_generation=payload["authoritySequence"],
            configuration_generation=payload["configurationSnapshot"]["configurationVersion"],
            revocation_generation=payload["membershipSnapshot"]["revocationGeneration"],
            authority_payload_digest=digest(payload),
            issuer_keys={"lease_fixture": _key(20)[1]},
            devices={device.device_id: device}, members={member.actor_id: member},
            authority_payload=payload, authority_signature=payload_row["signature"],
            authority_issuer_keys={"authority_fixture": _key(19)[1]},
            authority_checkpoints={device.device_id: (checkpoint, checkpoint_row["signature"])},
            enabled=True,
        )
    unsigned = {key: value for key, value in first_request.items() if key != "signature"}
    unsigned.update(afterSequence=1, priorEventDigest="e" * 64, requestNonce="9" * 64)
    signature = client_key.sign(canonical_json(unsigned).encode())
    request = {**unsigned, "signature": base64.urlsafe_b64encode(signature).decode().rstrip("=")}
    # Source-pinned test clock, never derived from the caller's HTTP body.
    now = datetime.fromtimestamp(1800000000.9, tz=timezone.utc)
    script = _NativeScript(authority, lease, now)
    provider = _Authorities(authority)
    active = True

    def peer(http_request: Request):
        if not active:
            return None
        return GatewayPeerAttestation(
            request=http_request, gateway_id="test-native-v41",
            workspace_id=authority.workspace_id, site_id=authority.site_id,
            device_id=device.device_id, client_fingerprint=device.client_fingerprint,
            session_generation=device.session_generation, observed_at=now,
        )

    resolver = ConnectedSiteGatewayPrincipalResolver(
        gateway_id="test-native-v41", load_attested_peer=peer,
        authority_provider=provider, now=lambda: now,
    )
    app = FastAPI()

    @app.post("/test-only/native-v41-feed")
    async def feed(http_request: Request):
        principal = resolver(http_request)
        if principal is None:
            raise HTTPException(status_code=401)
        try:
            return read_and_sign_test_only_page(
                connection_factory=script.connect, principal=principal,
                authority=authority, lease=lease, request=await http_request.json(),
                now=now, issuer_key_id="feed_fixture", issuer_seed=23,
            )
        except ConnectedSiteV15Error:
            raise HTTPException(status_code=403) from None

    with TestClient(app) as client:
        response = client.post("/test-only/native-v41-feed", json=request)
        if response.status_code != 200:
            raise ValueError(f"native_v41_http_rejected:{response.status_code}")
        sealed = response.json()
        if set(sealed) != {"requestJson", "pageJson", "proofJson"}:
            raise ValueError("native_v41_http_response_shape")
        if client.post("/test-only/native-v41-feed", json={**request, "deviceId": "wrong"}).status_code != 403:
            raise ValueError("native_v41_wrong_device_accepted")
        active = False
        if client.post("/test-only/native-v41-feed", json=request).status_code != 401:
            raise ValueError("native_v41_revoked_peer_accepted")
    return sealed


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("database", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    if not args.database.is_file() or args.output.exists():
        raise SystemExit("native_v41_fixture_paths_invalid")
    args.output.write_text(canonical_json(build_response(args.database)) + "\n", encoding="utf-8")
